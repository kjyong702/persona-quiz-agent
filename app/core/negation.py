"""부정 표현 감지. 임베딩이 확신한 정답을 한 번 더 의심하기 위한 것이다.

**왜 필요한가**

임베딩은 두 문장을 각자 벡터로 만들어 비교한다(바이인코더). 그래서 `"세종대왕"`과
`"세종대왕 아닙니다"`처럼 **부정어 하나만 다른 문장쌍의 거리를 벌리지 못한다.**
실측에서 부정문 오답이 유사도 0.926까지 나왔고, 이는 정답들보다도 높은 값이다.

앵커를 늘려도 안 풀린다. 부정문은 정답 표현을 그대로 포함하므로 앵커가 많아질수록
오히려 가까워진다. 구조에서 오는 한계라 같은 층위에서는 해결할 수 없다.

**무엇을 하고 무엇을 하지 않는가**

이 모듈은 **판정하지 않는다.** 부정 표현이 보이면 "임베딩만으로 확정하지 말고
LLM에게 물어보라"고 경로만 바꾼다. 규칙이 직접 오답 처리하면 반어법("서울 아니면
뭐예요?")이나 전언("아니라던데요")에서 틀린다.

이 설계의 안전성은 **오작동의 대가가 비대칭**이라는 데서 온다.

| 규칙이 틀렸을 때 | 결과 |
|---|---|
| 부정문이 아닌데 발동 | LLM을 한 번 더 부른다. **비용만 늘고 정확도 손해는 없다** |
| 부정문인데 미발동 | 원래 상태로 돌아갈 뿐, 더 나빠지지 않는다 |

즉 **최악의 경우가 "지금과 같음"**이다. 그래서 규칙 기반을 섞는 것이 정당화된다.

**패턴을 데이터로 정했다**

평가셋 372건에서 실제로 상한을 넘긴 부정문을 전부 뽑아 맞춰 만들었다. 추측이 아니다.
현재 규칙은 상한 통과 부정문 14건을 모두 잡고, 정답에 대한 실질 오작동은 없다
(`"쇠 아닌가요"` 한 건이 걸리지만 유사도가 상한 아래라 경로가 바뀌지 않는다).

**받침 때문에 한 번 틀렸다**

처음에 `아니|아냐`로 잡았더니 6건을 놓쳤다. `"아닙니다"`는 `아 + 닙 + 니 + 다`라서
부분 문자열 `"아니"`를 **포함하지 않는다.** 어간 `아니-`에 어미가 붙으면서 `니`에
받침이 들어가 다른 음절이 된다. 한국어를 문자열로 다룰 때 반복되는 함정이라,
활용형을 음절 집합으로 열거하는 쪽을 택했다.

**`없`, `않`, `안`은 일부러 뺐다**

14번 문항(`소리는 어떤 환경에서 전달되지 않나요?`)은 **질문 자체가 부정문이고 기대 정답도
부정 표현**이다(`공기가 없는 곳`, `진공에서는 전달되지 않습니다`). 이 계열을 규칙에
넣으면 정답 5건이 걸린다. 오답 부정문은 전부 `아니-` 계열이었으므로 거기서 끊었다.
"""

import re

# 어간 아니-의 활용형. 받침이 붙어 음절이 바뀌는 것까지 열거한다.
#   아니에요 / 아닙니다 / 아닌데요 / 아냐 / 아님
# `않`, `안`, `없`, `못`은 넣지 않는다. 기대 정답에 그 표현을 쓰는 문항이 있다
_NEGATION = re.compile(r"아[니닙닌냐님녜]")


def has_negation(text: str) -> bool:
    """부정 표현이 보이는가. 판정이 아니라 **의심의 근거**다."""
    return bool(_NEGATION.search(text))
